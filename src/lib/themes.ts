/** An uploaded theme as a theme card: its colours come from its own settings. */
export function customThemeDefinition(def: CustomThemeDef): ThemeDefinition {
  const c = def.content.settings;
  return {
    id: def.slug,
    slug: def.slug,
    name: def.name,
    tagline: def.tagline,
    tier: "free",
    category: def.category,
    previewImage: def.previewImage,
    description: def.description,
    previewColors: def.previewColors.length ? def.previewColors : [c.accent, c.background, c.text],
    tokens: { background: c.background, foreground: c.text, card: c.panel, primary: c.accent, primaryForeground: c.accentText, muted: c.panel, border: c.panel },
  };
}

/** Every theme sellers can pick: the built-in ones, then uploaded ones that are switched on. */
export function getAllThemes(): ThemeDefinition[] {
  return [
    ...Object.values(PLATFORM_THEMES),
    ...getCustomThemes()
      .filter((d) => d.enabled)
      .map(customThemeDefinition),
  ];
}

/** The theme for a slug; shops still set to a removed theme get Lume Editorial. */
export function getTheme(slug?: string): ThemeDefinition {
  const custom = getCustomTheme(slug);
  if (custom) return customThemeDefinition(custom);
  if (!slug) return PLATFORM_THEMES["classic-bloom"];
  const normalized = slug.replace(/^theme-(\d+)$/, "theme$1");
  return PLATFORM_THEMES[slug] || PLATFORM_THEMES[normalized] || PLATFORM_THEMES["classic-bloom"];
}

/**
 * A theme's thumbnail: a screenshot of its homepage as a buyer first sees it (public/theme-previews,
 * made from /themes/preview/<slug>?shot=1). Themes uploaded by the admin use their own preview image.
 */
export function themeThumb(theme: Pick<ThemeDefinition, "slug" | "previewImage">): string {
  if (getCustomTheme(theme.slug)) return theme.previewImage || "";
  const slug = theme.slug.replace(/^theme-(\d+)$/, "theme$1");
  return `/theme-previews/${slug}.webp`;
}
