#!/usr/bin/env node
/**
 * Cross-platform helper for the Android/iOS (Capacitor) apps. Works the same on Windows, macOS and Linux.
 *
 *   node scripts/mobile.mjs sync [--dev]            write mobile/www/config.js and run `cap sync`
 *   node scripts/mobile.mjs open <android|ios>      open Android Studio / Xcode
 *   node scripts/mobile.mjs run <android|ios> [--dev]  sync, then build and launch on a device/emulator
 *   node scripts/mobile.mjs gradle <task> [--dev]   sync, then run a Gradle task in android/
 *                                                   (assembleDebug | assembleRelease | bundleRelease)
 *   node scripts/mobile.mjs dev-server              start `next dev` reachable from phones on your Wi-Fi
 *
 * Settings come from environment variables, or from a `.env.mobile` file in the project root
 * (see `.env.mobile.example`). Real environment variables win over the file.
 *   CAP_SERVER_URL       production site the app loads (https)
 *   CAP_DEV_SERVER_URL   dev server for `--dev` builds (default: http://<this computer's LAN IP>:3000)
 */
import { spawnSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { networkInterfaces } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const isWindows = process.platform === "win32";
const args = process.argv.slice(2);
const dev = args.includes("--dev");
const [command, target] = args.filter((a) => !a.startsWith("--"));

loadEnvFile(path.join(root, ".env.mobile"));

function loadEnvFile(file) {
  if (!existsSync(file)) return;
  for (const line of readFileSync(file, "utf8").split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/i);
    if (!m || line.trim().startsWith("#")) continue;
    const value = m[2].replace(/^["']|["']$/g, "");
    if (process.env[m[1]] === undefined) process.env[m[1]] = value;
  }
}

function lanIp() {
  for (const list of Object.values(networkInterfaces())) {
    for (const a of list || []) {
      if (a.family === "IPv4" && !a.internal && !a.address.startsWith("169.254.")) return a.address;
    }
  }
  return null;
}

function run(cmd, cmdArgs, opts = {}) {
  const line = [cmd, ...cmdArgs].map((a) => (/\s/.test(a) ? `"${a}"` : a)).join(" ");
  console.log(`\n> ${line}`);
  // Windows needs a shell to start .cmd/.bat files (npx, gradlew.bat), so pass one quoted command line.
  const res = isWindows
    ? spawnSync(line, { stdio: "inherit", cwd: root, shell: true, ...opts })
    : spawnSync(cmd, cmdArgs, { stdio: "inherit", cwd: root, ...opts });
  if (res.status !== 0) process.exit(res.status ?? 1);
}

function capEnv() {
  const env = { ...process.env, CAP_ENV: dev ? "development" : "production" };
  if (dev && !env.CAP_DEV_SERVER_URL) {
    const ip = lanIp();
    if (ip) env.CAP_DEV_SERVER_URL = `http://${ip}:3000`;
  }
  return env;
}

function serverUrlFor(env) {
  return dev
    ? env.CAP_DEV_SERVER_URL || "http://10.0.2.2:3000"
    : env.CAP_SERVER_URL || "https://shopersite-app.vercel.app";
}

function sync() {
  const env = capEnv();
  const serverUrl = serverUrlFor(env);
  writeFileSync(
    path.join(root, "mobile/www/config.js"),
    `// Generated by scripts/mobile.mjs. Do not edit by hand.\nwindow.SHOPERSITE_APP = ${JSON.stringify({
      serverUrl,
      env: dev ? "development" : "production",
    })};\n`
  );
  console.log(`App will load: ${serverUrl} (${dev ? "development" : "production"})`);
  run("npx", ["cap", "sync"], { env });
  return env;
}

function requirePlatform() {
  if (target !== "android" && target !== "ios") {
    console.error("Say which platform: android or ios");
    process.exit(1);
  }
}

switch (command) {
  case "sync":
    sync();
    break;

  case "open":
    requirePlatform();
    run("npx", ["cap", "open", target]);
    break;

  case "run": {
    requirePlatform();
    const env = sync();
    run("npx", ["cap", "run", target], { env });
    break;
  }

  case "gradle": {
    if (!target) {
      console.error("Give a Gradle task, e.g. assembleDebug, assembleRelease or bundleRelease");
      process.exit(1);
    }
    sync();
    // Full path: Windows may not look in the current folder for commands (NoDefaultCurrentDirectoryInExePath)
    const androidDir = path.join(root, "android");
    const gradlew = path.join(androidDir, isWindows ? "gradlew.bat" : "gradlew");
    run(gradlew, [target], { cwd: androidDir });
    const outputs = {
      assembleDebug: ["android/app/build/outputs/apk/debug/app-debug.apk"],
      assembleRelease: [
        "android/app/build/outputs/apk/release/app-release.apk",
        "android/app/build/outputs/apk/release/app-release-unsigned.apk",
      ],
      bundleRelease: ["android/app/build/outputs/bundle/release/app-release.aab"],
    }[target];
    const out = outputs?.find((f) => existsSync(path.join(root, f)));
    if (out) console.log(`\nOutput: ${out}`);
    const hasKey = existsSync(path.join(root, "android/keystore.properties")) || !!process.env.ANDROID_KEYSTORE_FILE;
    if (target !== "assembleDebug" && !hasKey) {
      console.log("Note: no release key is configured, so this build is unsigned. See MOBILE_APP_SETUP.md section 4.4.");
    }
    break;
  }

  case "dev-server": {
    const ip = lanIp();
    const env = { ...process.env };
    if (ip) {
      env.NEXT_DEV_ALLOWED_ORIGINS = [env.NEXT_DEV_ALLOWED_ORIGINS, ip].filter(Boolean).join(",");
      console.log(`Phones on this Wi-Fi can reach the dev server at http://${ip}:3000`);
      console.log(`Build the app against it with: npm run cap:sync:dev   (or npm run android:run:dev)`);
    }
    run("npx", ["next", "dev", "-H", "0.0.0.0", "-p", "3000"], { env });
    break;
  }

  default:
    console.log(readFileSync(fileURLToPath(import.meta.url), "utf8").split("*/")[0]);
    process.exit(command ? 1 : 0);
}
